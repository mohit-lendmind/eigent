// Generates the TypeScript edge client from the versioned public contract
// mirror (src/api/aion/v1/contract/) into src/api/aion/v1/gen/:
//
//   edge-api.ts — openapi-typescript projection of openapi.yaml (paths +
//     component schema types; types only, erased at runtime).
//   meta.ts — runtime contract metadata: the compatibility tuple and the
//     documented x-aion-known-values sets (OPEN sets — a newer server may
//     emit values outside them; consumers pass unknowns through).
//
// Modes:
//   node scripts/gen-aion-edge-client.mjs           # write the files
//   node scripts/gen-aion-edge-client.mjs --check   # exit 1 on drift (CI)
//
// Both outputs are committed; the Bazel test //:aion_edge_client_gen runs
// --check so the generated client can never drift from the mirrored contract.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { parse as parseYAML } from 'yaml';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractDir = resolve(repoRoot, 'src/api/aion/v1/contract');
const genDir = resolve(repoRoot, 'src/api/aion/v1/gen');
const check = process.argv.includes('--check');

const banner = (source) => `// GENERATED by scripts/gen-aion-edge-client.mjs from ${source} — DO NOT EDIT.
// Regenerate with \`pnpm gen:aion-edge\` after syncing the contract mirror.
`;

function knownValues(schema, path) {
  let node = schema;
  for (const key of path) {
    node = node?.[key];
  }
  const values = node?.['x-aion-known-values'];
  if (!Array.isArray(values) || values.length === 0) {
    throw new Error(`x-aion-known-values missing at ${path.join('.')}`);
  }
  return values;
}

async function generate() {
  const openapiPath = resolve(contractDir, 'openapi.yaml');
  const openapiRaw = readFileSync(openapiPath, 'utf8');
  const openapi = parseYAML(openapiRaw);
  const compatibility = JSON.parse(
    readFileSync(resolve(contractDir, 'compatibility.json'), 'utf8')
  );

  const ast = await openapiTS(openapiRaw, { exportType: true });
  const edgeApi = banner('contract/openapi.yaml') + astToString(ast);

  const schemas = openapi.components.schemas;
  const eventKinds = knownValues(schemas, ['ProjectEvent', 'properties', 'kind']);
  const visibilities = knownValues(schemas, [
    'ProjectEvent',
    'properties',
    'visibility',
  ]);
  const runStatuses = knownValues(schemas, ['Run', 'properties', 'status']);

  const list = (values) =>
    values.map((v) => `  '${v}',`).join('\n');
  const meta = `${banner('contract/openapi.yaml + contract/compatibility.json')}
// The compatibility tuple the edge advertises (getIntegrationStatus and the
// X-Aion-Edge-Api-Version / X-Aion-Min-Desktop-Version headers).
export const EDGE_API_VERSION = '${compatibility.edge_api}' as const;
export const EVENT_SCHEMA_VERSION = '${compatibility.event_schema}' as const;
export const DESKTOP_CLIENT_VERSION = '${compatibility.desktop_client}' as const;
export const MINIMUM_SERVER_VERSION = '${compatibility.minimum_server}' as const;
export const MINIMUM_DESKTOP_VERSION = '${compatibility.minimum_desktop}' as const;

// x-aion-known-values: the values this contract version documents. All three
// sets are OPEN — additive contract evolution means a newer server may emit
// values outside them. Decode must pass unknowns through; rendering policy:
// unknown kind is opaque, unknown visibility is 'internal', unknown run
// status is busy/running (never terminal).
export const KNOWN_PROJECT_EVENT_KINDS = [
${list(eventKinds)}
] as const;

export const KNOWN_EVENT_VISIBILITIES = [
${list(visibilities)}
] as const;

export const KNOWN_RUN_STATUSES = [
${list(runStatuses)}
] as const;

export type KnownProjectEventKind = (typeof KNOWN_PROJECT_EVENT_KINDS)[number];
export type KnownEventVisibility = (typeof KNOWN_EVENT_VISIBILITIES)[number];
export type KnownRunStatus = (typeof KNOWN_RUN_STATUSES)[number];

// The set of run statuses that end a run. Anything else — known or unknown —
// renders as busy. Derived here so the reducer cannot invent its own idea of
// "terminal" that drifts from the contract.
export const TERMINAL_RUN_STATUSES = [
  'succeeded',
  'failed',
  'cancelled',
] as const satisfies readonly KnownRunStatus[];
`;

  return {
    'edge-api.ts': edgeApi,
    'meta.ts': meta,
  };
}

const outputs = await generate();
let drift = false;
for (const [name, content] of Object.entries(outputs)) {
  const path = resolve(genDir, name);
  if (check) {
    let existing = '';
    try {
      existing = readFileSync(path, 'utf8');
    } catch {
      // missing counts as drift
    }
    if (existing !== content) {
      drift = true;
      console.error(`DRIFT: ${name} does not match the contract mirror`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote src/api/aion/v1/gen/${name}`);
  }
}
if (check) {
  if (drift) {
    console.error(
      'Generated edge client is stale. Run `pnpm gen:aion-edge` and commit.'
    );
    process.exit(1);
  }
  console.log('generated edge client matches the contract mirror');
}
